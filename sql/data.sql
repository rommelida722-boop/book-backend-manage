-- -----------------------------------------------------------------------------
-- 导入自检：两表行数应分别为 8 和 12；第 1 页 5 行应与原卷图-1 一致
-- -----------------------------------------------------------------------------
SELECT 'book_type 行数' AS 检查项, COUNT(*) AS 行数 FROM book_type
UNION ALL
SELECT 'book_info 行数', COUNT(*) FROM book_info;

SELECT b.bookCode AS 图书编号,
       t.typeName AS 图书分类,
       b.bookName AS 图书名称,
       b.bookAuthor AS 作者,
       b.publishPress AS 出版社,
       DATE_FORMAT(b.creationTime, '%Y-%m-%d') AS 入库时间,
       IF(b.borrowed = 1, '已借阅', '未借阅') AS 是否借阅
  FROM book_info b
  JOIN book_type t ON t.id = b.bookType
 ORDER BY b.creationTime DESC
 LIMIT 5;
